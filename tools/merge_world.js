// merges data/world_*.json into js/worlddata.js (FCK.WORLD_DATA), compact
const fs = require('fs'), path = require('path');
const dir = path.join(__dirname, '..', 'data');
const files = fs.readdirSync(dir).filter((f) => /^world_\d+\.json$/.test(f)).sort();
const countries = [];
const seen = new Set();
files.forEach((f) => {
  const d = JSON.parse(fs.readFileSync(path.join(dir, f), 'utf8'));
  d.countries.forEach((c) => {
    if (seen.has(c.cc)) { console.log('duplicate country', c.cc, 'in', f); return; }
    seen.add(c.cc);
    // drop empty/unused fields
    c.leagues.forEach((l) => l.groups.forEach((g) => g.clubs.forEach((cl) => { if (!cl.st) delete cl.st; if (!cl.cap) delete cl.cap; if (!cl.c || !cl.c.length) delete cl.c; })));
    countries.push(c);
  });
});
const out = '/* generated by tools/merge_world.js - do not edit */\n(function (FCK) { FCK.WORLD_DATA = ' + JSON.stringify({ v: 1, countries }) + '; })((globalThis.FCK = globalThis.FCK || {}));\n';
fs.writeFileSync(path.join(__dirname, '..', 'js', 'worlddata.js'), out);
let n = 0; countries.forEach((c) => c.leagues.forEach((l) => l.groups.forEach((g) => { n += g.clubs.length; })));
console.log(files.length, 'files,', countries.length, 'countries,', n, 'clubs,', (out.length / 1024).toFixed(0), 'KB');
