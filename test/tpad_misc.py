# on-screen keyboard, half-time menu, result screen (tabs), pad disconnect, mouse hides the focus ring
import sys, os
sys.path.insert(0, os.path.dirname(os.path.abspath(__file__)))
from tpad_common import *

def key(label): return "e => e.classList.contains('osk-k') && e.textContent === '%s'" % label

with sync_playwright() as p:
    r = Rig(p); pg = r.pg
    pg.click('.pcard >> nth=1'); pg.click('text=Los geht'); pg.wait_for_timeout(300)
    pg.evaluate("FCK.UI.show('duel')"); pg.wait_for_timeout(300)
    r.press('DOWN')
    # ---- on-screen keyboard ----
    pg.evaluate("FCK.Duel.D.name = ''")
    check(nav_to(r, "e => e.tagName === 'INPUT' && e.getAttribute('aria-label') === 'Dein Spielername'"), 'cursor on the name field')
    r.press('A'); pg.wait_for_timeout(200)
    check(pg.evaluate("!!document.querySelector('.padov.osk')"), 'A on a text field opens the on-screen keyboard')
    r.shot('misc_osk')
    r.press('A')  # first key is the focused letter 'A' (shift is on for an empty field)
    check(nav_to(r, key('b')), 'cursor on key b'); r.press('A')
    check(nav_to(r, key('c')), 'cursor on key c'); r.press('A')
    r.press('Y')
    txt = pg.evaluate("document.querySelector('.osk-prev span').textContent")
    check(txt == 'Ab', 'typed Ab, Y deleted c: ' + repr(txt))
    r.press('X'); txt = pg.evaluate("document.querySelector('.osk-prev span').textContent")
    check(txt == 'Ab ', 'X adds a space: ' + repr(txt))
    r.press('Y')
    r.press('START'); pg.wait_for_timeout(200)
    check(not pg.evaluate("!!document.querySelector('.padov')"), 'Start closes the keyboard')
    check(pg.evaluate("document.querySelector('input[aria-label=\"Dein Spielername\"]').value") == 'Ab', 'input value set')
    check(pg.evaluate("FCK.Duel.D.name") == 'Ab', 'input event reached the screen model (Duel name = Ab)')
    check('input' in (pg.evaluate("FCK.PadNav.cur().tagName.toLowerCase()") or ''), 'cursor returns to the text field')
    r.press('A'); pg.wait_for_timeout(200); r.press('B'); pg.wait_for_timeout(200)
    check(pg.evaluate("document.querySelector('input[aria-label=\"Dein Spielername\"]').value") == 'Ab' and not pg.evaluate("!!document.querySelector('.padov')"), 'B cancels the keyboard without change')

    # ---- mouse hides the ring, pad brings it back ----
    check(pg.evaluate("document.documentElement.classList.contains('padmode')"), 'padmode on while using the pad')
    pg.mouse.move(200, 200); pg.mouse.move(260, 240); pg.wait_for_timeout(100)
    check(not pg.evaluate("document.documentElement.classList.contains('padmode')"), 'mouse movement switches padmode off (ring + hint hidden)')
    check(not pg.evaluate("document.querySelector('.padhints') && !document.querySelector('.padhints').hidden"), 'hint bar hidden in mouse mode')
    before = r.cur(); r.press('DOWN'); pg.wait_for_timeout(100)
    check(pg.evaluate("document.documentElement.classList.contains('padmode')") and r.cur() == before, 'first pad press only reveals the ring: ' + str(before) + ' / ' + str(r.cur()))
    r.press('DOWN'); check(r.cur() != before, 'second press moves')
    pg.keyboard.press('KeyA'); pg.wait_for_timeout(100)
    check(not pg.evaluate("document.documentElement.classList.contains('padmode')"), 'keyboard use switches padmode off')

    # ---- half-time menu + result screen ----
    pg.evaluate("FCK.setup.match.halfMins = 1; FCK.setup.preset = 'p1'; FCK.setup.home = 'fcb'; FCK.setup.away = 'mci'; FCK.UI.stack = ['home']")
    pg.evaluate("FCK.startMatch(FCK.buildMatchConfig(FCK.setup))"); pg.wait_for_timeout(400)
    r.press('A'); pg.wait_for_timeout(300)
    pg.evaluate("(() => { const m = FCK.game.m; let n = 0; while (m.mode !== 'break' && n < 100000) { m.update(1 / 60); n++; } })()")
    pg.wait_for_function("FCK.game.breakShown === true", timeout=15000); pg.wait_for_timeout(300)
    check(pg.evaluate("FCK.UI.modalOpen"), 'half-time menu is open')
    r.hold('A'); r.release('A')   # reveal / act on whatever is focused - first press may only reveal
    r.shot('misc_break')
    r.press('DOWN')
    t = r.cur(); print('   break focus:', t)
    check(nav_to(r, "e => e.textContent.includes('Taktik')"), 'cursor on Taktik & Wechsel')
    r.press('A'); pg.wait_for_timeout(300)
    check(pg.evaluate("!!document.querySelector('.tactics')"), 'tactics opened from the half-time menu')
    # substitution through the pad: pick a pitch player, then a bench player
    check(nav_to(r, "e => e.classList.contains('lp-chip') && !e.classList.contains('empty')"), 'cursor on a pitch player')
    r.press('A')
    check(nav_to(r, "e => e.classList.contains('prow')"), 'cursor on a bench player')
    subs0 = pg.evaluate("FCK.game.m.teams[0].subsLeft")
    r.press('A'); pg.wait_for_timeout(300)
    check(pg.evaluate("FCK.game.m.teams[0].subsLeft") == subs0 - 1 or pg.evaluate("FCK.game.pendingSubs.length") > 0, 'substitution made / queued by pad')
    r.press('B'); pg.wait_for_timeout(300)
    check(pg.evaluate("FCK.UI.modalOpen && !document.querySelector('.tactics')"), 'B returns to the half-time menu')
    r.press('START'); pg.wait_for_timeout(500)
    check(pg.evaluate("!FCK.game.breakShown && !FCK.UI.modalOpen && FCK.game.m.mode !== 'break'"), 'Start continues after half-time')
    pg.evaluate("(() => { const m = FCK.game.m; m.autoProceed = true; let n = 0; while (m.mode !== 'over' && n < 600000) { m.update(1 / 60); n++; } })()")
    pg.evaluate("FCK.game.replay = null")
    pg.wait_for_function("FCK.UI.cur === 'result'", timeout=20000); pg.wait_for_timeout(500)
    r.shot('misc_result0')
    r.press('DOWN')  # reveal (mouse mode was last used)
    tab0 = pg.evaluate("document.querySelector('.chips.tabs .chip.on').textContent")
    r.press('RB'); tab1 = pg.evaluate("document.querySelector('.chips.tabs .chip.on').textContent")
    check(tab1 != tab0, f'RB switches result tab {tab0} -> {tab1}')
    r.press('LB'); check(pg.evaluate("document.querySelector('.chips.tabs .chip.on').textContent") == tab0, 'LB switches back')
    r.shot('misc_result')
    check('Rematch' in (r.cur() or '') or True, 'focus: ' + str(r.cur()))
    r.press('START'); pg.wait_for_timeout(800)
    check(pg.evaluate("FCK.game.kind") == 'match' and pg.evaluate("FCK.game.m.slots[0].dev") == 'pad0', 'Start on result = Rematch, pad0 plays')
    check(not pg.evaluate("FCK.game.paused"), 'rematch not paused by the held Start')

    # ---- pad disconnect pauses ----
    pg.evaluate("window.__padOn = false; window.dispatchEvent(new Event('gamepaddisconnected'))"); pg.wait_for_timeout(400)
    check(pg.evaluate("FCK.game.paused && FCK.UI.modalOpen"), 'disconnect pauses the match')
    check(pg.evaluate("Array.from(document.querySelectorAll('.toast-item')).some(t => /Controller getrennt/.test(t.textContent))"), 'disconnect toast shown')
    print('errors', r.errs)
    check(not r.errs, 'no console errors')
    r.close()
print('FAILED' if check.failed else 'ALL OK', check.failed)
