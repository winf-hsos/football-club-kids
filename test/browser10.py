import os as _os
_ROOT = _os.path.abspath(_os.path.join(_os.path.dirname(__file__), '..'))
_OUT = _os.path.join(_os.environ.get('FCK_SHOTS', _os.path.join(_os.environ.get('TMPDIR', '/tmp'), 'fck-shots')), '')
_os.makedirs(_OUT, exist_ok=True)
from playwright.sync_api import sync_playwright
OUT=_OUT
with sync_playwright() as p:
    b=p.chromium.launch(executable_path='/opt/pw-browsers/chromium', args=['--no-sandbox'])
    ctx=b.new_context(viewport={'width':390,'height':800}, locale='de-DE')
    pg=ctx.new_page()
    errs=[]
    pg.on('console', lambda m: errs.append(m.type+': '+m.text) if m.type in ('error','warning') and 'ERR_FAILED' not in m.text else None)
    pg.on('pageerror', lambda e: errs.append('PAGEERR '+str(e)))
    pg.route('**/*', lambda r: r.abort() if r.request.url.startswith('http') else r.continue_())
    pg.goto(('file://' + _ROOT + '/dist/FCK.html'))
    pg.wait_for_timeout(1000)
    pg.click('.pcard >> nth=0'); pg.click('text=Los geht'); pg.wait_for_timeout(400)   # kids profile
    pg.click('.mitem:has-text("Karriere")'); pg.wait_for_timeout(300)
    pg.click('text=Neue Karriere >> nth=0'); pg.wait_for_timeout(300)
    pg.click('button:has-text("Verein wählen") >> nth=0'); pg.wait_for_timeout(400)
    pg.fill('input[type=search]', 'Bayern'); pg.wait_for_timeout(300)
    (pg.click('.picker-grid .pick >> nth=0') if pg.query_selector('#modal .pick') else pg.click('#modal .pk-ok')); pg.wait_for_timeout(300)
    pg.screenshot(path=OUT+'h0_new.png')
    pg.click('text=Karriere starten'); pg.wait_for_timeout(900)
    print('kids easy', pg.evaluate("FCK.Career.cur.m.easy"))
    pg.screenshot(path=OUT+'h1_hub.png', full_page=True)
    for tab in ['Kader','Transfers','Jugend','Verein']:
        pg.click('.chips.tabs .chip:has-text("%s")'%tab); pg.wait_for_timeout(500)
        pg.screenshot(path=OUT+'h2_%s.png'%tab)
        print(tab, 'hscroll', pg.evaluate("document.documentElement.scrollWidth>window.innerWidth"))
    pg.click('.chips.tabs .chip:has-text("Kader")'); pg.wait_for_timeout(300)
    pg.click('table.mg tbody tr >> nth=2'); pg.wait_for_timeout(300)
    pg.screenshot(path=OUT+'h3_player.png')
    pg.click('#modal button:has-text("Schließen")')
    pg.click('button:has-text("Aufstellung")'); pg.wait_for_timeout(300)
    pg.screenshot(path=OUT+'h4_lineup.png')
    pg.click('#modal button:has-text("Abbrechen")')
    pg.click('.chips.tabs .chip:has-text("Transfers")'); pg.wait_for_timeout(300)
    pg.click('button:has-text("Suchen")'); pg.wait_for_timeout(900)
    pg.click('.mrow >> nth=1'); pg.wait_for_timeout(300)
    pg.screenshot(path=OUT+'h5_market.png')
    pg.click('#modal button:has-text("Schließen")')
    # force sacked flow
    pg.evaluate("FCK.Career.cur.m.easy=false; FCK.Career.cur.m.sacked=true; FCK.MgrUI._sackShown=false; FCK.UI.show('career',null,true)")
    pg.wait_for_timeout(600)
    pg.screenshot(path=OUT+'h6_sacked.png')
    pg.click('#modal button:has-text("Neuen Verein wählen")'); pg.wait_for_timeout(400)
    pg.fill('input[type=search]', 'Osnabr'); pg.wait_for_timeout(300)
    (pg.click('.picker-grid .pick >> nth=0') if pg.query_selector('#modal .pick') else pg.click('#modal .pk-ok')); pg.wait_for_timeout(800)
    print('new club', pg.evaluate("FCK.World.clubs[FCK.Career.cur.idx].name"), 'sacked', pg.evaluate("FCK.Career.cur.m.sacked"))
    pg.screenshot(path=OUT+'h7_newclub.png')
    print('\n'.join(errs) or 'no errors')
    b.close()
