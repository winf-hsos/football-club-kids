import os as _os
_ROOT = _os.path.abspath(_os.path.join(_os.path.dirname(__file__), '..'))
_OUT = _os.path.join(_os.environ.get('FCK_SHOTS', _os.path.join(_os.environ.get('TMPDIR', '/tmp'), 'fck-shots')), '')
_os.makedirs(_OUT, exist_ok=True)
from playwright.sync_api import sync_playwright
OUT=_OUT
with sync_playwright() as p:
    b=p.chromium.launch(executable_path='/opt/pw-browsers/chromium', args=['--no-sandbox'])
    ctx=b.new_context(viewport={'width':1280,'height':800}, locale='de-DE')
    pg=ctx.new_page()
    errs=[]
    pg.on('console', lambda m: errs.append(m.type+': '+m.text) if m.type in ('error','warning') and 'ERR_FAILED' not in m.text else None)
    pg.on('pageerror', lambda e: errs.append('PAGEERR '+str(e)))
    pg.route('**/*', lambda r: r.abort() if r.request.url.startswith('http') else r.continue_())
    pg.goto(('file://' + _ROOT + '/dist/FCK.html'))
    pg.wait_for_timeout(1000)
    pg.click('.pcard >> nth=1'); pg.click('text=Los geht'); pg.wait_for_timeout(400)
    pg.click('.mitem:has-text("Karriere")'); pg.wait_for_timeout(300)
    pg.click('text=Neue Karriere >> nth=0'); pg.wait_for_timeout(300)
    pg.click('button:has-text("Verein wählen") >> nth=0'); pg.wait_for_timeout(400)
    pg.fill('input[type=search]', 'Osnabr'); pg.wait_for_timeout(300)
    (pg.click('.picker-grid .pick >> nth=0') if pg.query_selector('#modal .pick') else pg.click('#modal .pk-ok')); pg.wait_for_timeout(300)
    pg.click('button:has-text("Voll")'); pg.wait_for_timeout(200)
    pg.screenshot(path=OUT+'e0_new.png')
    pg.click('text=Karriere starten'); pg.wait_for_timeout(900)
    pg.screenshot(path=OUT+'e1_hub.png')
    for tab in ['Kader','Transfers','Jugend','Verein']:
        pg.click('.chips.tabs .chip:has-text("%s")'%tab); pg.wait_for_timeout(500)
        pg.screenshot(path=OUT+'e2_%s.png'%tab)
    # player dialog
    pg.click('.chips.tabs .chip:has-text("Kader")'); pg.wait_for_timeout(300)
    pg.click('table.mg tbody tr >> nth=3'); pg.wait_for_timeout(300)
    pg.screenshot(path=OUT+'e3_player.png')
    pg.click('#modal button:has-text("Schließen")'); pg.wait_for_timeout(200)
    pg.click('button:has-text("Aufstellung")'); pg.wait_for_timeout(300)
    pg.screenshot(path=OUT+'e4_lineup.png')
    pg.click('#modal button:has-text("OK")'); pg.wait_for_timeout(300)
    print('after lineup', pg.evaluate("JSON.stringify(FCK.Career.cur.m.xi && FCK.Career.cur.m.xi.ids)"))
    # transfers
    pg.click('.chips.tabs .chip:has-text("Transfers")'); pg.wait_for_timeout(300)
    pg.click('button:has-text("Suchen")'); pg.wait_for_timeout(900)
    pg.screenshot(path=OUT+'e5_search.png')
    pg.click('.mrow >> nth=0'); pg.wait_for_timeout(300)
    pg.screenshot(path=OUT+'e6_market.png')
    pg.click('#modal button:has-text("Angebot abgeben")'); pg.wait_for_timeout(300)
    pg.screenshot(path=OUT+'e7_bid.png')
    pg.click('#modal button:has-text("Schließen")'); pg.wait_for_timeout(200)
    for sub in ['Scouting','Vereinslose','Angebote','Verlauf']:
        pg.click('.chips.tabs.sm .chip:has-text("%s")'%sub); pg.wait_for_timeout(300)
        pg.screenshot(path=OUT+'e8_%s.png'%sub)
    pg.click('.chips.tabs.sm .chip:has-text("Scouting")'); pg.wait_for_timeout(300)
    pg.click('button:has-text("Auftrag starten")'); pg.wait_for_timeout(300)
    pg.screenshot(path=OUT+'e9_scout.png')
    pg.click('.chips.tabs .chip:has-text("Verein")'); pg.wait_for_timeout(300)
    for sub in ['Finanzen','Ausbau','Presse']:
        pg.click('.chips.tabs.sm .chip:has-text("%s")'%sub); pg.wait_for_timeout(300)
        pg.screenshot(path=OUT+'f0_%s.png'%sub)
    pg.click('button:has-text("Vor dem Spiel")'); pg.wait_for_timeout(300)
    pg.screenshot(path=OUT+'f1_press.png')
    pg.click('#modal .btn.wide >> nth=0'); pg.click('#modal .btn.wide >> nth=1'); pg.click('#modal .btn.wide >> nth=2'); pg.wait_for_timeout(300)
    pg.screenshot(path=OUT+'f2_pressdone.png')
    pg.click('#modal button:has-text("OK")'); pg.wait_for_timeout(300)
    # sim a few + play one
    pg.click('.chips.tabs .chip:has-text("Übersicht")'); pg.wait_for_timeout(300)
    for i in range(4):
        pg.click('button:has-text("Simulieren") >> nth=0'); pg.wait_for_timeout(300)
    pg.screenshot(path=OUT+'f3_home.png')
    print('state', pg.evaluate("JSON.stringify({cash:FCK.Career.cur.m.cash, bc:FCK.Career.cur.m.bc, inj:FCK.Career.cur.m.players.filter(p=>p.inj).length, news:FCK.Career.cur.news.slice(0,4).map(n=>FCK.T(n.k,n.v))})"))
    pg.click('button:has-text("Spielen")'); pg.wait_for_timeout(600)
    pg.wait_for_function("FCK.game.m && FCK.game.m.mode==='play' && FCK.game.m.clock>20", timeout=60000)
    pg.screenshot(path=OUT+'f4_match.png')
    print('match players', pg.evaluate("FCK.game.m.teams.map(t=>t.players.slice(0,3).map(p=>p.d.name+' '+p.d.ovr+' sqi'+p.d.sqi).join(', '))"))
    pg.evaluate("""(()=>{const m=FCK.game.m; m.autoProceed=true; let n=0; while(m.mode!=='over'&&n<600000){ m.update(1/60); n++; } return n;})()""")
    pg.evaluate("FCK.game.replay=null")
    pg.wait_for_function("FCK.UI.cur==='result'", timeout=15000)
    pg.wait_for_timeout(400)
    pg.screenshot(path=OUT+'f5_result.png')
    pg.click('text=Weiterspielen'); pg.wait_for_timeout(800)
    print('lastXI', pg.evaluate("JSON.stringify(FCK.Career.cur.m.lastXI)"), 'ap', pg.evaluate("FCK.Career.cur.m.players.filter(p=>p.ap>0).length"))
    pg.screenshot(path=OUT+'f6_afterplay.png')
    # rest of season
    pg.click('button:has-text("Saison simulieren") >> nth=0'); pg.wait_for_timeout(300)
    pg.click('.modal button:has-text("Saison simulieren")'); pg.wait_for_timeout(2500)
    pg.screenshot(path=OUT+'g0_seasonend.png')
    pg.click('button:has-text("Neue Saison starten")'); pg.wait_for_timeout(800)
    pg.screenshot(path=OUT+'g1_review.png')
    pg.click('#modal button:has-text("Neue Saison beginnen")'); pg.wait_for_timeout(1500)
    pg.screenshot(path=OUT+'g2_newseason.png')
    pg.evaluate("document.querySelector('#modal .modal').scrollTop=9999")
    pg.screenshot(path=OUT+'g3_newseason2.png')
    pg.click('#modal button:has-text("OK")'); pg.wait_for_timeout(500)
    pg.screenshot(path=OUT+'g4_hub2.png')
    print('stored bytes', pg.evaluate("(localStorage.getItem('fck.cauto')||'').length"))
    print('\n'.join(errs) or 'no errors')
    b.close()
