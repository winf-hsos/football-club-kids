import os as _os
_ROOT = _os.path.abspath(_os.path.join(_os.path.dirname(__file__), '..'))
_OUT = _os.path.join(_os.environ.get('FCK_SHOTS', _os.path.join(_os.environ.get('TMPDIR', '/tmp'), 'fck-shots')), '')
_os.makedirs(_OUT, exist_ok=True)
from playwright.sync_api import sync_playwright
import sys
OUT=_OUT
MOBILE = len(sys.argv)>1 and sys.argv[1]=='m'
P = 'm_' if MOBILE else 'd_'
with sync_playwright() as p:
    b=p.chromium.launch(executable_path='/opt/pw-browsers/chromium', args=['--no-sandbox'])
    ctx=b.new_context(viewport={'width':390,'height':1800} if MOBILE else {'width':1180,'height':1500}, locale='de-DE')
    pg=ctx.new_page()
    errs=[]
    pg.on('console', lambda m: errs.append(m.type+': '+m.text) if m.type in ('error','warning') and 'ERR_FAILED' not in m.text else None)
    pg.on('pageerror', lambda e: errs.append('PAGEERR '+str(e)))
    pg.route('**/*', lambda r: r.abort() if r.request.url.startswith('http') else r.continue_())
    pg.goto(('file://' + _ROOT + '/dist/FCK.html'))
    pg.wait_for_timeout(1000)
    pg.click('.pcard >> nth=1'); pg.click('text=Los geht'); pg.wait_for_timeout(400)
    pg.screenshot(path=OUT+P+'k0_menu.png')
    pg.click('.mitem:has-text("Karten-Modus")'); pg.wait_for_timeout(700)
    pg.screenshot(path=OUT+P+'k1_home.png', full_page=True)
    def hs(tag): print(tag, 'hscroll', pg.evaluate("(()=>{const s=document.getElementById('screen');return s.scrollWidth>s.clientWidth+1})()"))
    hs('home')
    # daily gift
    if pg.locator('button:has-text("Abholen")').count(): pg.click('button:has-text("Abholen") >> nth=0'); pg.wait_for_timeout(300)
    print('packs', pg.evaluate("JSON.stringify(FCK.Cards.S.inv)"))
    # team tab
    pg.click('.chips.tabs .chip:has-text("Aufstellung")'); pg.wait_for_timeout(500)
    pg.screenshot(path=OUT+P+'k2_team.png', full_page=True); hs('team')
    for f in ['4-4-2','3-5-2','4-2-3-1','5-3-2']:
        pg.click('.chips >> text="%s"' % f); pg.wait_for_timeout(250)
        pg.screenshot(path=OUT+P+'k2_team_%s.png' % f.replace('-',''), full_page=True)
    pg.click('.chips >> text="4-3-3"'); pg.wait_for_timeout(250)
    pg.click('.slot-w .fc >> nth=9'); pg.wait_for_timeout(400)
    pg.screenshot(path=OUT+P+'k3_pick.png')
    pg.click('#modal .crow >> nth=0'); pg.wait_for_timeout(400)
    pg.click('button:has-text("Auto-Aufstellung")'); pg.wait_for_timeout(400)
    # shop + open pack
    pg.click('.chips.tabs .chip:has-text("Shop")'); pg.wait_for_timeout(400)
    pg.screenshot(path=OUT+P+'k4_shop.png', full_page=True); hs('shop')
    pg.evaluate("FCK.Cards.S.coins=60000; FCK.Cards.save(); FCK.CardsUI.redraw()"); pg.wait_for_timeout(300)
    pg.click('.pack >> nth=3 >> button:has-text("Kaufen & öffnen")'); pg.wait_for_timeout(600)
    pg.screenshot(path=OUT+P+'k5_pack_closed.png')
    pg.click('#modal button:has-text("Alle aufdecken")'); pg.wait_for_timeout(2600)
    pg.screenshot(path=OUT+P+'k6_pack_open.png')
    pg.click('#modal button:has-text("Fertig")'); pg.wait_for_timeout(300)
    pg.click('.pack >> nth=4 >> button:has-text("Kaufen & öffnen")'); pg.wait_for_timeout(500)
    pg.click('#modal button:has-text("Alle aufdecken")'); pg.wait_for_timeout(2600)
    pg.screenshot(path=OUT+P+'k6b_legend_pack.png')
    pg.click('#modal button:has-text("Fertig")'); pg.wait_for_timeout(300)
    # collection
    pg.click('.chips.tabs .chip:has-text("Sammlung")'); pg.wait_for_timeout(600)
    pg.screenshot(path=OUT+P+'k7_coll.png', full_page=True); hs('coll')
    pg.click('.cgrid .fc >> nth=0'); pg.wait_for_timeout(300)
    pg.screenshot(path=OUT+P+'k8_card.png')
    pg.click('#modal button:has-text("Auf den Markt stellen")'); pg.wait_for_timeout(300)
    pg.screenshot(path=OUT+P+'k8b_list.png')
    pg.click('#modal button:has-text("Anbieten")'); pg.wait_for_timeout(500)
    print('listed', pg.evaluate("FCK.Cards.S.list.length"))
    # market
    pg.click('.chips.tabs .chip:has-text("Markt")'); pg.wait_for_timeout(500)
    pg.click('.chips >> text="Angebote"'); pg.wait_for_timeout(300)
    pg.screenshot(path=OUT+P+'k9_market.png', full_page=True); hs('market')
    before = pg.evaluate("FCK.Cards.S.cards.length")
    pg.click('.crow >> button:has-text("Kaufen") >> nth=0'); pg.wait_for_timeout(500)
    print('bought', pg.evaluate("FCK.Cards.S.cards.length")-before)
    pg.click('.chips >> text=/Meine Angebote/'); pg.wait_for_timeout(300)
    pg.screenshot(path=OUT+P+'k9b_mine.png', full_page=True)
    # tasks
    pg.click('.chips.tabs .chip:has-text("Aufgaben")'); pg.wait_for_timeout(500)
    pg.screenshot(path=OUT+P+'k10_tasks.png', full_page=True); hs('tasks')
    # swaps
    pg.click('.chips.tabs .chip:has-text("Tausch")'); pg.wait_for_timeout(500)
    pg.screenshot(path=OUT+P+'k11_sbc.png', full_page=True); hs('sbc')
    pg.click('.task.sbc >> button:has-text("Karten wählen") >> nth=1'); pg.wait_for_timeout(400)
    pg.screenshot(path=OUT+P+'k12_sbc_dialog.png')
    pg.evaluate("document.querySelectorAll('#modal .crow')[0].click()"); pg.wait_for_timeout(200)
    pg.click('#modal button:has-text("Abbrechen")'); pg.wait_for_timeout(200)
    # club
    pg.click('.chips.tabs .chip:has-text("Club")'); pg.wait_for_timeout(500)
    pg.fill('.cardsmode input.txt', 'Sternenkicker')
    pg.click('.swatch >> nth=5'); pg.wait_for_timeout(300)
    pg.screenshot(path=OUT+P+'k13_club.png', full_page=True); hs('club')
    pg.click('button:has-text("Sammlung exportieren")'); pg.wait_for_timeout(300)
    pg.screenshot(path=OUT+P+'k13b_export.png')
    txt = pg.evaluate("document.querySelector('#modal textarea').value")
    print('export len', len(txt), txt[:8])
    pg.click('#modal button:has-text("Schließen")')
    # play a ladder match (spectate, 1 min halves) and finish headless-fast
    pg.evaluate("FCK.Cards.S.preset='cpu'; FCK.Cards.S.half=1; FCK.Cards.save()")
    pg.click('.chips.tabs .chip:has-text("Start")'); pg.wait_for_timeout(500)
    pg.click('button:has-text("Spielen")'); pg.wait_for_timeout(800)
    pg.wait_for_function("FCK.game.m && FCK.game.m.mode==='play' && FCK.game.m.clock>10", timeout=60000)
    pg.screenshot(path=OUT+P+'k14_match.png')
    print('home club in match', pg.evaluate("FCK.game.m.teams[0].name"), 'players', pg.evaluate("FCK.game.m.teams[0].players.map(p=>p.d.name.split(' ').pop()+':'+p.d.ovr).join(' ')"))
    pg.evaluate("""(()=>{const m=FCK.game.m; m.autoProceed=true; let n=0; while(m.mode!=='over'&&n<600000){ m.update(1/60); n++; } return n;})()""")
    pg.evaluate("FCK.game.replay=null")
    pg.wait_for_function("FCK.UI.cur==='result'", timeout=15000)
    pg.wait_for_timeout(500)
    pg.screenshot(path=OUT+P+'k15_result.png', full_page=True)
    print('after', pg.evaluate("JSON.stringify({st:FCK.Cards.S.st, rank:FCK.Cards.S.rank, last:FCK.Cards.S.last && {res:FCK.Cards.S.last.res,coins:FCK.Cards.S.last.coins}})"))
    pg.click('button:has-text("Weiter")'); pg.wait_for_timeout(600)
    print('screen after continue', pg.evaluate("FCK.UI.cur"))
    pg.screenshot(path=OUT+P+'k16_home_after.png', full_page=True)
    # persistence: reload keeps the collection
    n = pg.evaluate("FCK.Cards.S.cards.length")
    pg.reload(); pg.wait_for_timeout(1200)
    print('after reload cards', pg.evaluate("(FCK.Cards.ensure(), FCK.Cards.S.cards.length)"), 'was', n, 'name', pg.evaluate("FCK.Cards.S.team.name"))
    # english
    pg.evaluate("FCK.settings.lang='en'; FCK.saveSettings(); FCK.UI.show('cards',null,true)"); pg.wait_for_timeout(500)
    pg.screenshot(path=OUT+P+'k17_en.png', full_page=True)
    print('errors:', errs if errs else 'none')
    b.close()
