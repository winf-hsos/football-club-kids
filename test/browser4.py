import os as _os
_ROOT = _os.path.abspath(_os.path.join(_os.path.dirname(__file__), '..'))
_OUT = _os.path.join(_os.environ.get('FCK_SHOTS', _os.path.join(_os.environ.get('TMPDIR', '/tmp'), 'fck-shots')), '')
_os.makedirs(_OUT, exist_ok=True)
import time
from playwright.sync_api import sync_playwright
OUT=_OUT
with sync_playwright() as p:
    b=p.chromium.launch(executable_path='/opt/pw-browsers/chromium', args=['--no-sandbox'])
    ctx=b.new_context(viewport={'width':1280,'height':720}, locale='de-DE')
    pg=ctx.new_page()
    errs=[]
    pg.on('console', lambda m: errs.append(m.type+': '+m.text) if m.type in ('error','warning') and 'ERR_FAILED' not in m.text else None)
    pg.on('pageerror', lambda e: errs.append('PAGEERR '+str(e)))
    pg.route('**/*', lambda r: r.abort() if r.request.url.startswith('http') else r.continue_())
    pg.goto(('file://' + _ROOT + '/dist/FCK.html'))
    pg.wait_for_timeout(800)
    pg.click('.pcard >> nth=1'); pg.click('text=Los geht'); pg.wait_for_timeout(400)
    pg.click('text=Freundschaftsspiel'); pg.wait_for_timeout(300)
    pg.click('text=Zuschauen')
    pg.evaluate("FCK.setup.match.halfMins=3; FCK.setup.match.tod='evening'")
    pg.click('text=Anstoß')
    pg.wait_for_function("FCK.game.m && FCK.game.m.mode==='play' && FCK.game.m.clock>150", timeout=90000)
    pg.screenshot(path=OUT+'g0_play.png')
    pg.evaluate("(()=>{const m=FCK.game.m;const b=m.ball;b.owner=null;b.x=-0.6;b.y=34;b.z=0.4;b.vx=-6;b.vy=0;b.vz=0;b.lastTouch=m.teams[1].players[9];m.lastTouchTeam=1;})()")
    pg.wait_for_timeout(1800)
    pg.screenshot(path=OUT+'g1_goal.png')
    pg.wait_for_function("FCK.game.replay", timeout=15000)
    pg.wait_for_timeout(2500)
    pg.screenshot(path=OUT+'g2_replay.png')
    pg.keyboard.press('Space'); pg.wait_for_timeout(800)
    print('replay after skip:', pg.evaluate("!!FCK.game.replay"), 'mode', pg.evaluate("FCK.game.m.mode"))
    pg.wait_for_timeout(2500)
    pg.keyboard.press('Escape'); pg.wait_for_timeout(500)
    pg.screenshot(path=OUT+'g3_pause.png')
    pg.click('text=Weiterspielen'); pg.wait_for_timeout(500)
    print('clips', pg.evaluate("FCK.Archive.list().length"))
    pg.keyboard.press('Escape'); pg.wait_for_timeout(300)
    pg.click('text=Spiel verlassen'); pg.click('text=Wirklich verlassen'); pg.wait_for_timeout(800)
    pg.click('text=Highlights'); pg.wait_for_timeout(500)
    pg.screenshot(path=OUT+'g4_highlights.png')
    pg.click('text=Ansehen'); pg.wait_for_timeout(2500)
    pg.screenshot(path=OUT+'g5_archive.png')
    print('\n'.join(errs[:20]) or 'no errors')
    b.close()
