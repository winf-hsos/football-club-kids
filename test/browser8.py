import os as _os
_ROOT = _os.path.abspath(_os.path.join(_os.path.dirname(__file__), '..'))
_OUT = _os.path.join(_os.environ.get('FCK_SHOTS', _os.path.join(_os.environ.get('TMPDIR', '/tmp'), 'fck-shots')), '')
_os.makedirs(_OUT, exist_ok=True)
from playwright.sync_api import sync_playwright
OUT=_OUT
with sync_playwright() as p:
    b=p.chromium.launch(executable_path='/opt/pw-browsers/chromium', args=['--no-sandbox'])
    ctx=b.new_context(viewport={'width':1280,'height':720}, locale='de-DE')
    pg=ctx.new_page()
    errs=[]
    pg.on('console', lambda m: errs.append(m.type+': '+m.text) if m.type in ('error','warning') and 'ERR_FAILED' not in m.text else None)
    pg.on('pageerror', lambda e: errs.append('PAGEERR '+str(e)))
    pg.route('**/*', lambda r: r.abort() if r.request.url.startswith('http') else r.continue_())
    pg.goto(('file://' + _ROOT + '/dist/FCK.html'))
    pg.wait_for_timeout(1000)
    pg.click('.pcard >> nth=1'); pg.click('text=Los geht'); pg.wait_for_timeout(400)
    pg.click('text=Freundschaftsspiel'); pg.wait_for_timeout(400)
    pg.screenshot(path=OUT+'d0_setup.png')
    print(pg.evaluate("Object.keys(FCK.setup)"))
    pg.click('button:has-text("Verein wechseln") >> nth=1'); pg.wait_for_timeout(500)
    pg.screenshot(path=OUT+'d1_picker.png')
    pg.fill('input[type=search]', 'Dortmund'); pg.wait_for_timeout(300)
    (pg.click('.picker-grid .pick >> nth=0') if pg.query_selector('#modal .pick') else pg.click('#modal .pk-ok')); pg.wait_for_timeout(500)
    pg.click('text=Zuschauen'); pg.wait_for_timeout(300)
    pg.evaluate("FCK.setup.match.halfMins=2")
    pg.screenshot(path=OUT+'d2_setup.png')
    pg.click('text=Anstoß')
    pg.wait_for_function("FCK.game.m && FCK.game.m.mode==='play' && FCK.game.m.clock>30", timeout=60000)
    print(pg.evaluate("FCK.game.m.teams.map(t=>t.club.name+': '+t.players.slice(0,4).map(p=>p.name+' '+p.ovr).join(', '))"))
    pg.screenshot(path=OUT+'d3_match.png')
    pg.keyboard.press('Escape'); pg.click('text=Spiel verlassen'); pg.click('text=Wirklich verlassen'); pg.wait_for_timeout(600)
    # career: import dialog
    pg.click('.mitem:has-text("Karriere")'); pg.wait_for_timeout(300)
    pg.click('text=Echte Spielerdaten'); pg.wait_for_timeout(300)
    pg.fill('textarea', 'club;name;pos;ovr;age;nat\nFC Bayern München;Test Neuer;GK;90;38;de\nBVB;Test Kane;ST;91;30;en\nXyz FC;Nobody;ST;70;20;de')
    pg.click("#modal button:has-text(\"Importieren\")"); pg.wait_for_timeout(300)
    pg.screenshot(path=OUT+'d5_import.png')
    print(pg.evaluate("document.querySelector('.modal').innerText.slice(-160)"), 'count', pg.evaluate("FCK.Import.count()"))
    pg.click("#modal button:has-text(\"Schließen\")"); pg.wait_for_timeout(200)
    pg.click('text=Neue Karriere >> nth=0'); pg.wait_for_timeout(300)
    pg.click('button:has-text("Verein wählen") >> nth=0'); pg.wait_for_timeout(400)
    pg.fill('input[type=search]', 'Bayern'); pg.wait_for_timeout(300)
    (pg.click('.picker-grid .pick >> nth=0') if pg.query_selector('#modal .pick') else pg.click('#modal .pk-ok')); pg.wait_for_timeout(300)
    pg.click('text=Karriere starten'); pg.wait_for_timeout(800)
    pg.click('.chips.tabs .chip:has-text("Kader")'); pg.wait_for_timeout(300)
    pg.screenshot(path=OUT+'d6_squad.png')
    print(pg.evaluate("document.body.innerText.includes('Test Neuer')"))
    # mobile
    pg.set_viewport_size({'width':390,'height':800}); pg.wait_for_timeout(400)
    for tab in ['Übersicht','Tabelle','Spielplan','Welt']:
        pg.click('.chips.tabs .chip:has-text("%s")'%tab); pg.wait_for_timeout(300)
        pg.screenshot(path=OUT+'m_%s.png'%tab)
    print('hscroll', pg.evaluate("document.documentElement.scrollWidth>window.innerWidth"))
    b.close()
    print('\n'.join(errs) or 'no errors')
